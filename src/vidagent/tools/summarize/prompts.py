def build_meta_block(metadata: dict) -> str:
    """【标题】+【简介】元数据块——各管线请求文本的公共前缀。"""
    if not metadata:
        return ""
    return f"【标题】{metadata.get('title', '')}\n【简介】{metadata.get('desc', '')}\n"
